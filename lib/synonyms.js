/** 把表展开成 Map，方便查。 */
const MAP = new Map(SYNONYMS.map(([k, v]) => [k, v]));

/**
 * 给一组检索词补上同义说法。
 * 只在「原词命中数太少」时才有意义，所以不做任何剪枝。
 * @param {string[]} tokens 已经切好的词
 * @returns {string[]} 原词 + 补出来的说法（去重）
 */
export function expandTokens(tokens) {
  const out = new Set(tokens);
  for (const t of tokens) {
    const extra = MAP.get(t);
    if (extra) for (const e of extra) out.add(e);
  }
  return [...out];
}
