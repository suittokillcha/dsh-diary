//   用户嘴里说的是「大肥鱼不敢下水」，可那天的原文和摘要里写的是「不敢走出去」「伸了一只脚进去」。
//   「下水」两个字，在 11-01 那天的原文里出现 0 次、摘要里也 0 次。
//   拿他的原话去搜，命中率低得可怕。所以要把「他的话」翻译成「我们当时的说法」再搜。
// 维护：跑一段时间看哪条没兜住就往里加，不用一次写全。
// 注意：只做单向扩展（他的话 → 补出更多候选词），不改写他的原话。

